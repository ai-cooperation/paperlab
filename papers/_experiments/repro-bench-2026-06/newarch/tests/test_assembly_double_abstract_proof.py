"""THE PROOF (ADR-001 slice 1): the known double-Abstract shape cannot survive the
deterministic assembly path.

golden_paper is the real fixture with the production defect shape: the draft carries
a body `# Abstract` section while the springer/frontmatter surface carries its own
abstract — the exact class that shipped double-Abstract PDFs past floor-86 gates and
was only caught by a human at the VIP checkpoint. This test drives it through
migrate -> assemble -> springer derivation and asserts the abstract exists exactly
once per surface, with zero stub text, on BOTH surfaces.
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path

from engine_v3.assembly import ir_render_values, migrate_legacy_run
import render_springer

FIXTURE = Path(__file__).parent / "fixtures" / "golden_paper"


def _copy_fixture(tmp_path: Path) -> Path:
    for name in ("paper_draft_v0.qmd", "references.bib", "research_contract.json"):
        src = FIXTURE / name
        if src.is_file():
            shutil.copy2(src, tmp_path / name)
    return tmp_path


def _abstract_headings(text: str) -> int:
    return len(re.findall(r"(?m)^#{1,3}\s*Abstract\b", text))


def test_golden_double_abstract_shape_is_eliminated(tmp_path: Path) -> None:
    run = _copy_fixture(tmp_path)
    original = (run / "paper_draft_v0.qmd").read_text(encoding="utf-8")
    assert _abstract_headings(original) == 1  # fixture: body Abstract present (the defect DNA)

    result = migrate_legacy_run(run)
    assert result.ok, result.blocked_findings

    # Surface 1 — generated draft: exactly ONE Abstract heading, no frontmatter
    # abstract key, no stub, banner present.
    draft = (run / "paper_draft_v0.qmd").read_text(encoding="utf-8")
    assert _abstract_headings(draft) == 1
    frontmatter = draft.split("---")[1]
    assert not re.search(r"(?m)^abstract:", frontmatter)
    assert "Abstract pending" not in draft
    assert draft.startswith("<!-- GENERATED by engine_v3.assembly")

    # Surface 2 — springer derivation via IR values (no regex extraction): exactly
    # ONE frontmatter abstract, ZERO body Abstract headings, no stub.
    ir_values = ir_render_values(run)
    assert ir_values is not None
    springer_path = render_springer.normalize_frontmatter(run, {}, ir_values=ir_values)
    springer = springer_path.read_text(encoding="utf-8")
    s_front, s_body = springer.split("---\n\n", 1)
    assert len(re.findall(r"(?m)^abstract:", s_front)) == 1
    assert _abstract_headings(s_body) == 0
    assert "Abstract pending" not in springer
    # the real abstract text made it into the frontmatter
    assert "OpenAlex" in s_front or "abstract-level" in s_front


def test_stub_frontmatter_springer_is_regenerated_clean(tmp_path: Path) -> None:
    """The retro-job breakout shape: a pre-existing springer with an 'Abstract
    pending.' stub frontmatter. The new derivation OVERWRITES it from the IR."""
    run = _copy_fixture(tmp_path)
    (run / "paper_springer.qmd").write_text(
        "---\ntitle: x\nabstract: |\n  Abstract pending.\n---\n\nbody\n", encoding="utf-8"
    )
    assert migrate_legacy_run(run).ok
    springer_path = render_springer.normalize_frontmatter(run, {}, ir_values=ir_render_values(run))
    springer = springer_path.read_text(encoding="utf-8")
    assert "Abstract pending" not in springer


def test_legacy_extraction_path_unchanged_without_meta(tmp_path: Path) -> None:
    """Transition guard: without paper_meta.json the springer derivation behaves
    exactly as before (extraction path) — in-flight legacy jobs are untouched."""
    run = _copy_fixture(tmp_path)
    springer_path = render_springer.normalize_frontmatter(run, {}, ir_values=None)
    springer = springer_path.read_text(encoding="utf-8")
    assert len(re.findall(r"(?m)^abstract:", springer.split("---\n\n", 1)[0])) == 1
