"""Layout adapters: turn a domain IR into the generated qmd for one output shape.

ADR-001 §3 (domain-generality guard, D4): the assembler operates ONLY on the IR and
delegates artifact SHAPE to a layout adapter selected by `ir.layout`. All
paper/elsarticle/heading knowledge lives here, never in the assembler core. Adding a
`slides` or `report` domain = a new adapter registered below + its own IR — zero
change to assembler.py.

Every adapter MUST honor two structural invariants the whole ecosystem depends on:
- the frontmatter block is the FIRST bytes (`\\A---`); the GENERATED banner comes
  AFTER it (a leading comment broke the frontmatter anchor and leaked YAML into the
  render body — live proof 2026-07-09).
- the abstract is emitted EXACTLY ONCE per surface, wrapped in its source-map markers.
"""
from __future__ import annotations

from typing import Callable

from .ir import PaperDraftIR

GENERATED_BANNER = (
    "<!-- GENERATED by engine_v3.assembly - edit sections/*.md + paper_meta.json, "
    "never this file (it is overwritten on every assemble) -->"
)


def _source_open(rel: str) -> str:
    return "<!-- SOURCE: %s -->" % rel


def _source_close(rel: str) -> str:
    return "<!-- END SOURCE: %s -->" % rel


def render_paper(ir: PaperDraftIR) -> str:
    """The `paper` layout: elsarticle-bound draft qmd — one `## Abstract` body
    section then the ordered sections, every block source-mapped."""
    author_yaml = "".join(
        "  - name: %s\n%s" % (a.name, ("    email: %s\n" % a.email) if a.email else "")
        for a in ir.authors
    )
    parts = [
        "---",
        'title: "%s"' % ir.title.replace('"', "'"),
        "author:",
        author_yaml.rstrip("\n"),
        "bibliography: %s" % ir.bibliography,
        "format:",
        "  pdf:",
        "    pdf-engine: xelatex",
        "number-sections: true",
        "link-citations: true",
        "---",
        "",
        GENERATED_BANNER,
        "",
        _source_open(ir.abstract_ref),
        "## Abstract",
        "",
        ir.abstract,
        _source_close(ir.abstract_ref),
        "",
    ]
    for section in ir.sections:
        parts.extend([_source_open(section.rel_path), section.text, _source_close(section.rel_path), ""])
    parts.append("## References")
    return "\n".join(parts) + "\n"


# layout name -> adapter. New domains register here; the assembler never branches on
# layout itself (D4 litmus: adding a domain requires zero assembler changes).
_LAYOUTS: dict[str, Callable[[PaperDraftIR], str]] = {
    "paper": render_paper,
}


def render_ir(ir: PaperDraftIR) -> str:
    adapter = _LAYOUTS.get(ir.layout)
    if adapter is None:
        raise ValueError(
            "no layout adapter for layout %r (registered: %s)"
            % (ir.layout, sorted(_LAYOUTS))
        )
    return adapter(ir)
